const I18NContext = React.createContext({ lang: 'en', name: '', t: (k) => I18N.en[k] || k });
function useT() { return React.useContext(I18NContext); }
// Interpolate {name} etc. Pass vars as 2nd arg: t('greet_afternoon', { name: 'Lena' })
function I18NProvider({ lang, name, children }) {
  const dict = I18N[lang] || I18N.en;
  const t = React.useCallback((k, vars) => {
    const raw = dict[k] || I18N.en[k] || k;
    const merged = { name: name || '', ...(vars || {}) };
    return raw.replace(/\{(\w+)\}/g, (_, key) => (merged[key] != null ? merged[key] : `{${key}}`));
  }, [dict, name]);
  return <I18NContext.Provider value={{ lang, name, t }}>{children}</I18NContext.Provider>;
}
